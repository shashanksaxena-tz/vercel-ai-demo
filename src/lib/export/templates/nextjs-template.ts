/**
 * Next.js Page Template
 *
 * Provides template structures for generating Next.js App Router
 * page components with metadata and proper conventions.
 */

import type { UIFramework } from '@/types';

/**
 * Next.js template configuration options
 */
export interface NextJSTemplateOptions {
  pageName: string;
  pageTitle: string;
  pageDescription: string;
  framework: UIFramework;
  includeTypes: boolean;
  includeMetadata: boolean;
  isServerComponent: boolean;
}

/**
 * Generate metadata export for Next.js pages
 */
export function generateMetadataExport(title: string, description: string): string {
  return `import type { Metadata } from 'next';

export const metadata: Metadata = {
  title: '${title}',
  description: '${description}',
};
`;
}

